/**
 * Non-Planar G-code Generator for Lampshades
 * Targets Bambu Lab A1 Mini (Marlin-flavor, direct drive, 180x180x180 build volume)
 *
 * Key A1 Mini specs:
 *  - Build volume: 180 x 180 x 180 mm
 *  - Direct drive extruder (short retraction ~0.8mm)
 *  - Firmware: Marlin-compatible
 *  - Nozzle: 0.4mm default
 *  - Heated bed
 *  - Auto bed leveling
 *  - Uses absolute extrusion by default
 */
const GcodeGenerator = (() => {

    /**
     * Generate complete G-code for the lampshade.
     *
     * @param {Array} rings — ring data from LampshadeGeometry.generate()
     * @param {Object} params — all user parameters
     * @returns {{ gcode: string, stats: Object, toolpaths: Array }}
     */
    function generate(rings, params) {
        const {
            height = 100,
            sides = 64,
            layerHeight = 0.16,
            wallThickness = 0.8,
            nozzleTemp = 215,
            bedTemp = 60,
            printSpeed = 40,
            filamentDiameter = 1.75,
            nozzleDiameter = 0.4,
            retractionDist = 0.8,
            patternType = 'none',
            patternScale = 10,
            patternDepth = 50,
            baseRings = 3,
            lipRings = 2,
            spiralMode = false,
            waveAmplitude = 1.5,
        } = params;

        const lines = [];
        const toolpaths = []; // For 3D preview: array of layers, each a list of points
        let E = 0; // Cumulative extrusion
        let lastX = 0, lastY = 0, lastZ = 0;
        let totalMoves = 0;

        const filamentArea = Math.PI * (filamentDiameter / 2) ** 2;
        const nozzleArea = nozzleDiameter * layerHeight; // simplified cross-section

        // Extrusion multiplier: volume-based
        const extrusionWidth = nozzleDiameter * 1.05; // slight over-extrusion for adhesion
        const extrusionMultiplier = (extrusionWidth * layerHeight) / filamentArea;

        function emitLine(text) {
            lines.push(text);
        }

        function moveTo(x, y, z, f) {
            emitLine(`G0 X${x.toFixed(3)} Y${y.toFixed(3)} Z${z.toFixed(3)} F${f}`);
            lastX = x; lastY = y; lastZ = z;
        }

        function extrudeTo(x, y, z, f) {
            const dx = x - lastX;
            const dy = y - lastY;
            const dz = z - lastZ;
            const dist = Math.sqrt(dx * dx + dy * dy + dz * dz);
            E += dist * extrusionMultiplier;
            emitLine(`G1 X${x.toFixed(3)} Y${y.toFixed(3)} Z${z.toFixed(3)} E${E.toFixed(5)} F${f}`);
            lastX = x; lastY = y; lastZ = z;
            totalMoves++;
        }

        function retract() {
            if (retractionDist > 0) {
                E -= retractionDist;
                emitLine(`G1 E${E.toFixed(5)} F${(40 * 60).toFixed(0)}`);
            }
        }

        function unretract() {
            if (retractionDist > 0) {
                E += retractionDist;
                emitLine(`G1 E${E.toFixed(5)} F${(40 * 60).toFixed(0)}`);
            }
        }

        // === START G-CODE (A1 Mini compatible) ===
        emitLine('; Generated by Lampshade Generator — Non-Planar G-code');
        emitLine('; Target: Bambu Lab A1 Mini');
        emitLine(`; Layer height: ${layerHeight}mm`);
        emitLine(`; Wall thickness: ${wallThickness}mm`);
        emitLine(`; Non-planar amplitude: ${waveAmplitude}mm`);
        emitLine(`; Pattern: ${patternType}`);
        emitLine('');
        emitLine('; ====== START GCODE ======');
        emitLine('G90 ; Absolute positioning');
        emitLine('M82 ; Absolute extrusion');
        emitLine(`M104 S${nozzleTemp} ; Set nozzle temp`);
        emitLine(`M140 S${bedTemp} ; Set bed temp`);
        emitLine(`M190 S${bedTemp} ; Wait for bed temp`);
        emitLine(`M109 S${nozzleTemp} ; Wait for nozzle temp`);
        emitLine('G28 ; Home all axes');
        emitLine('G29 ; Auto bed leveling');
        emitLine('G92 E0 ; Reset extruder');
        emitLine('');
        emitLine('; Prime line');
        emitLine('G1 Z2.0 F3000');
        emitLine('G1 X5 Y5 F3000');
        emitLine('G1 Z0.3 F1000');
        emitLine('G1 X60 Y5 E10 F1500');
        emitLine('G1 X60 Y5.4 E10.2 F1500');
        emitLine('G1 X5 Y5.4 E20 F1500');
        emitLine('G92 E0 ; Reset extruder after prime');
        emitLine('');
        E = 0;

        // Build plate centre offset (A1 Mini: 180x180, centre at 90,90)
        const centreX = 90;
        const centreY = 90;

        const feedRate = printSpeed * 60; // mm/s to mm/min
        const travelRate = 150 * 60;
        const firstLayerFeed = Math.min(feedRate, 20 * 60);

        const layerCount = rings.length - 1;
        const wallPasses = Math.max(1, Math.round(wallThickness / nozzleDiameter));

        // === LAYER LOOP ===
        for (let layer = 0; layer <= layerCount; layer++) {
            const ring = rings[layer];
            const t = layer / layerCount; // normalized height
            const isBaseRegion = layer < baseRings * Math.ceil(1 / layerHeight);
            const isLipRegion = layer > layerCount - lipRings * Math.ceil(1 / layerHeight);
            const currentFeed = layer < 3 ? firstLayerFeed : feedRate;

            emitLine('');
            emitLine(`; ====== LAYER ${layer} Z~${(ring[0].z).toFixed(2)} ======`);

            const layerPath = [];

            // Determine number of wall passes for this layer
            const passes = (isBaseRegion || isLipRegion) ? wallPasses + 1 : wallPasses;

            for (let pass = 0; pass < passes; pass++) {
                // Offset radius inward for multi-wall passes
                const offsetFraction = pass * nozzleDiameter;

                if (spiralMode && pass === 0 && !isBaseRegion && !isLipRegion) {
                    // Spiral (vase) mode: continuous Z interpolation within one layer
                    for (let s = 0; s < sides; s++) {
                        const pt = ring[s];
                        // Interpolate Z between this layer and next
                        const nextZ = (layer < layerCount) ? rings[layer + 1][s].z : pt.z;
                        const interpZ = pt.z + (nextZ - pt.z) * (s / sides);

                        const r = pt.radius - offsetFraction;
                        if (r <= 0) continue;

                        const x = centreX + r * Math.cos(pt.angle);
                        const y = centreY + r * Math.sin(pt.angle);
                        const z = interpZ;

                        // Pattern-based wall thickness
                        const u = s / sides;
                        const v = t;
                        const wallMult = Patterns.sample(patternType, u, v, patternScale, patternDepth);

                        if (wallMult < 0.1 && !isBaseRegion && !isLipRegion) {
                            // Skip this segment (open pattern)
                            retract();
                            moveTo(x, y, z, travelRate);
                            unretract();
                        } else {
                            if (s === 0 && pass === 0) {
                                retract();
                                moveTo(x, y, z, travelRate);
                                unretract();
                            }
                            extrudeTo(x, y, z, currentFeed);
                        }

                        layerPath.push({ x, y: z, z: y, extrude: wallMult >= 0.1 });
                    }
                } else {
                    // Standard layer-by-layer mode
                    let needsTravel = true;

                    for (let s = 0; s <= sides; s++) {
                        const idx = s % sides;
                        const pt = ring[idx];
                        const r = pt.radius - offsetFraction;
                        if (r <= 0) continue;

                        const x = centreX + r * Math.cos(pt.angle);
                        const y = centreY + r * Math.sin(pt.angle);
                        const z = pt.z; // Non-planar Z!

                        const u = idx / sides;
                        const v = t;
                        const wallMult = Patterns.sample(patternType, u, v, patternScale, patternDepth);

                        if (wallMult < 0.1 && !isBaseRegion && !isLipRegion) {
                            if (!needsTravel) {
                                retract();
                                needsTravel = true;
                            }
                            layerPath.push({ x, y: z, z: y, extrude: false });
                            continue;
                        }

                        if (needsTravel) {
                            moveTo(x, y, z, travelRate);
                            unretract();
                            needsTravel = false;
                        }

                        extrudeTo(x, y, z, currentFeed);
                        layerPath.push({ x, y: z, z: y, extrude: true });
                    }

                    if (!needsTravel) {
                        retract();
                    }
                }
            }

            toolpaths.push(layerPath);
        }

        // === END G-CODE ===
        emitLine('');
        emitLine('; ====== END GCODE ======');
        emitLine('G91 ; Relative positioning');
        emitLine('G1 E-2 F1800 ; Retract');
        emitLine('G1 Z10 F3000 ; Lift nozzle');
        emitLine('G90 ; Absolute positioning');
        emitLine('G1 X5 Y170 F9000 ; Move to back corner');
        emitLine('M104 S0 ; Turn off nozzle heater');
        emitLine('M140 S0 ; Turn off bed heater');
        emitLine('M107 ; Fan off');
        emitLine('M84 ; Disable motors');
        emitLine('; Done!');

        const totalFilamentMm = E;
        const totalFilamentM = E / 1000;
        const estimatedMinutes = (totalMoves / (printSpeed * 60)) * 60 + layerCount * 0.5;

        const stats = {
            layers: layerCount,
            lines: lines.length,
            filamentMm: totalFilamentMm.toFixed(1),
            filamentM: totalFilamentM.toFixed(2),
            estimatedMinutes: Math.ceil(estimatedMinutes),
            estimatedTime: formatTime(estimatedMinutes),
        };

        return {
            gcode: lines.join('\n'),
            stats,
            toolpaths,
        };
    }

    function formatTime(minutes) {
        const hrs = Math.floor(minutes / 60);
        const mins = Math.ceil(minutes % 60);
        if (hrs > 0) return `${hrs}h ${mins}m`;
        return `${mins}m`;
    }

    /**
     * Validate parameters against A1 Mini build volume.
     * Returns array of warning strings, empty if all OK.
     */
    function validate(params) {
        const warnings = [];
        const maxXY = 180;
        const maxZ = 180;
        const maxR = Math.max(params.bottomDiameter, params.topDiameter) / 2;

        if (maxR * 2 > maxXY) {
            warnings.push(`Diameter ${maxR * 2}mm exceeds A1 Mini bed width (${maxXY}mm)`);
        }
        if (params.height > maxZ) {
            warnings.push(`Height ${params.height}mm exceeds A1 Mini build height (${maxZ}mm)`);
        }
        if (params.waveAmplitude > params.layerHeight * 3) {
            warnings.push(`Wave amplitude ${params.waveAmplitude}mm is >3x layer height — may cause nozzle collisions`);
        }
        if (params.height + params.waveAmplitude > maxZ) {
            warnings.push(`Total height with waves (${(params.height + params.waveAmplitude).toFixed(1)}mm) exceeds build volume`);
        }
        return warnings;
    }

    return { generate, validate };
})();
